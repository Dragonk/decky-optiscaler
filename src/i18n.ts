/**
 * UI translations. English is the source language: every user-facing
 * string in the components is written in English and passed through
 * `t()`. When the language resolved from the Steam client is Polish,
 * `t()` looks the source string up in `PL` and returns the translation;
 * anything missing falls back to the English source. `{0}`, `{1}`, ...
 * in a pattern are replaced with the positional arguments.
 *
 * Intentionally NOT translated: `config/generatedSchema.ts` (generated),
 * `config/labels.ts` (mirrors the wording of OptiScaler's own in-game
 * overlay, so a setting can be recognised there) and `config/keys.ts`
 * (physical key names).
 */

import { useSyncExternalStore } from "react";

export type Lang = "en" | "pl";

let current: Lang = "en";
const listeners = new Set<() => void>();

/** The UI language, for the few call sites that need to branch on it. */
export function lang(): Lang {
  return current;
}

/** Set the UI language; subscribed components re-render at once. */
export function setLang(next: Lang): void {
  if (next === current) return;
  current = next;
  listeners.forEach((fn) => fn());
}

/** Subscribe to language changes (for useSyncExternalStore). */
export function subscribeLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Re-render on language change; call once in a root component. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribeLang, lang);
}

/** Translate `source`, substituting `{0}`, `{1}`, ... with `args`. */
export function t(source: string, args?: unknown[]): string {
  let text = current === "pl" ? PL[source] ?? source : source;
  if (args) {
    args.forEach((a, i) => {
      text = text.split("{" + i + "}").join(String(a));
    });
  }
  return text;
}

/**
 * Polish plural form: 1 -> one, 2-4 -> few, otherwise many. Polish has no
 * single "add s" rule like English, so counted strings use this helper.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const last = Math.abs(n) % 10;
  const hundreds = Math.abs(n) % 100;
  if (last >= 2 && last <= 4 && (hundreds < 12 || hundreds > 14)) return few;
  return many;
}

